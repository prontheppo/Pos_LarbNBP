-- TABLE: public.cost_product_prices
CREATE TABLE IF NOT EXISTS public.cost_product_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT,
    supplier_id BIGINT,
    price BIGINT
);

-- TABLE: public.cost_products
CREATE TABLE IF NOT EXISTS public.cost_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT
);

-- TABLE: public.cost_suppliers
CREATE TABLE IF NOT EXISTS public.cost_suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT
);

-- TABLE: public.customer_groups
CREATE TABLE IF NOT EXISTS public.customer_groups (
    customer_group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_group_name TEXT
);

-- TABLE: public.customers
CREATE TABLE IF NOT EXISTS public.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT
);

-- TABLE: public.food_groups
CREATE TABLE IF NOT EXISTS public.food_groups (
    food_group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_group_name TEXT
);

-- TABLE: public.food_stock
CREATE TABLE IF NOT EXISTS public.food_stock (
    food_stock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_stock_name TEXT,
    quantity BIGINT,
    updated_at TIMESTAMPTZ
);

-- TABLE: public.foods
CREATE TABLE IF NOT EXISTS public.foods (
    food_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_name TEXT,
    food_group_id BIGINT,
    price_1 BIGINT,
    price_2 BIGINT,
    price_3 BIGINT
);

-- TABLE: public.location_food_prices
CREATE TABLE IF NOT EXISTS public.location_food_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT,
    food_id BIGINT,
    custom_price BIGINT,
    created_at TIMESTAMPTZ,
    price TEXT
);

-- TABLE: public.location_zone
CREATE TABLE IF NOT EXISTS public.location_zone (
    zone_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_name TEXT,
    location_id BIGINT
);

-- TABLE: public.locations
CREATE TABLE IF NOT EXISTS public.locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_name TEXT,
    min_order_for_free_delivery BIGINT,
    delivery_fee BIGINT
);

-- TABLE: public.menu_food_stock
