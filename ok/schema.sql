    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_id BIGINT,
    food_stock_id BIGINT
);

-- TABLE: public.orders
CREATE TABLE IF NOT EXISTS public.orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ,
    total_price BIGINT,
    total_qty BIGINT,
    items JSONB,
    customer_name TEXT,
    customer_type_id BIGINT,
    note TEXT,
    location_id BIGINT,
    zone_id BIGINT,
    delivery_fee BIGINT,
    subtotal BIGINT,
    customer_id TEXT
